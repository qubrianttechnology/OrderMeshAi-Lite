"""Opt-in sample workspace. Credentials are supplied interactively or via environment."""

import argparse
import getpass
import os
from datetime import timedelta

from sqlalchemy import select, text

from .config import settings
from .db import SessionLocal
from .main import create_order
from .models import (
    Customer,
    Membership,
    Order,
    Organization,
    Product,
    StockMovement,
    User,
    now,
)
from .schemas import OrderInput
from .security import Tenant, passwords


def seed(email, password, organization="Serendib Distributors"):
    if settings.app_env == "production":
        raise RuntimeError("Sample data is disabled in production")
    if len(password) < 12:
        raise ValueError("Provide a password of at least 12 characters")
    with SessionLocal() as db:
        if db.bind.dialect.name != "sqlite":
            raise RuntimeError(
                "Sample workspace seeding is restricted to local SQLite databases."
            )
        if db.scalar(select(User).where(User.email == email.lower())):
            raise ValueError(
                "This email already exists. Use a new email; seed never overwrites accounts."
            )
        user = User(
            email=email.lower(),
            name="Workspace Owner",
            password_hash=passwords.hash(password),
        )
        org = Organization(name=organization)
        db.add_all([user, org])
        db.flush()
        db.add(Membership(user_id=user.id, organization_id=org.id, role="owner"))
        if db.bind.dialect.name == "postgresql":
            db.execute(
                text("SELECT set_config('app.organization_id', :id, true)"),
                {"id": org.id},
            )
        customers = [
            Customer(organization_id=org.id, name=name, phone=phone, address=address)
            for name, phone, address in [
                ("Perera Stores", "011 234 5678", "Nugegoda, Colombo"),
                ("Lakmini Traders", "081 234 5678", "Kandy"),
                ("New City Mart", "091 234 5678", "Galle"),
                ("Saman Grocery", "037 234 5678", "Kurunegala"),
                ("Greenway Super", "031 234 5678", "Negombo"),
            ]
        ]
        products = [
            Product(
                organization_id=org.id,
                name=name,
                sku=sku,
                aliases=aliases,
                unit=unit,
                price_minor=price,
                stock=stock,
                reorder_level=reorder,
            )
            for name, sku, aliases, unit, price, stock, reorder in [
                (
                    "Nadu Rice",
                    "RICE-001",
                    ["Rice", "හාල්", "සහල්"],
                    "bags",
                    125000,
                    85,
                    15,
                ),
                ("White Sugar", "SUG-001", ["Sugar", "සීනි"], "bags", 145000, 62, 12),
                ("Red Dhal", "DHAL-001", ["Dhal", "පරිප්පු"], "bags", 172000, 54, 10),
                ("Coconut Oil", "OIL-001", ["Oil", "පොල් තෙල්"], "bottles", 68000, 9, 12),
                ("Wheat Flour", "FLR-001", ["Flour", "පිටි"], "bags", 110000, 7, 10),
                ("Ceylon Tea", "TEA-001", ["Tea", "තේ"], "packs", 48000, 40, 10),
                ("Chilli Powder", "CHI-001", ["Chilli", "මිරිස්"], "packs", 32000, 8, 10),
                ("Milk Powder", "MLK-001", ["Milk", "කිරි පිටි"], "packs", 105000, 35, 8),
            ]
        ]
        db.add_all([*customers, *products])
        db.flush()
        for p in products:
            db.add(
                StockMovement(
                    organization_id=org.id,
                    product_id=p.id,
                    delta=p.stock,
                    reason="Sample opening stock",
                    created_by=user.id,
                )
            )
        db.commit()
        tenant = Tenant(org.id, user.id, "owner")
        # Explicit sample manual orders, never generated by extraction.
        for i in range(14):
            if db.bind.dialect.name == "postgresql":
                db.execute(
                    text("SELECT set_config('app.organization_id', :id, true)"),
                    {"id": org.id},
                )
            product = products[i % 3]
            quantity = 1 + i % 4
            body = OrderInput(
                customer_id=customers[i % 5].id,
                items=[{"product_id": product.id, "quantity": quantity}],
                human_confirmed=True,
                expected_total_minor=product.price_minor * quantity,
            )
            result = create_order(body, f"sample-order-{i}", tenant, db)
            if db.bind.dialect.name == "postgresql":
                db.execute(
                    text("SELECT set_config('app.organization_id', :id, true)"),
                    {"id": org.id},
                )
            order = db.scalar(
                select(Order).where(
                    Order.organization_id == org.id, Order.id == result["id"]
                )
            )
            order.created_at = now() - timedelta(days=6 - i // 2, hours=i % 2)
            if i < 9:
                order.status = "fulfilled"
            db.commit()
        return org.id


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Create an isolated sample workspace (development only)"
    )
    parser.add_argument("--email", required=True)
    parser.add_argument("--organization", default="Serendib Distributors")
    args = parser.parse_args()
    supplied = os.environ.get("SEED_PASSWORD") or getpass.getpass(
        "Choose sample account password (12+ characters): "
    )
    print(
        f"Sample workspace created: {seed(args.email, supplied, args.organization)}. Sign in with the supplied email and password."
    )
